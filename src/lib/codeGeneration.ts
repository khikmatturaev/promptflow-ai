const MAX_ARTIFACTS = 120;
const MAX_SOURCE_LINES = 240;

const COMPUTE_TYPES: ArchitectureNodeType[] = ["backend", "api", "service", "worker"];

const slug = (value: string): string =>
    value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48) || "component";

const unique = <T,>(items: T[]): T[] => [...new Set(items)];

function identifier(value: string): string {
    const base = slug(value).replace(/-([a-z])/g, (_, c: string) => c.toUpperCase()).replace(/[^a-zA-Z0-9_$]/g, "");
    return /^[a-zA-Z_$]/.test(base) ? base : `component${base}`;
}

function typeIdentifier(value: string): string {
    const base = identifier(value);
    return base.charAt(0).toUpperCase() + base.slice(1);
}

function nodeById(nodes: ArchitectureNode[]): Map<string, ArchitectureNode> {
    return new Map(nodes.map((node) => [node.id, node]));
}

function framework(nodes: ArchitectureNode[]): { framework: string; runtime: string; extension: string } {
    const text = nodes.map((node) => `${node.data.label} ${node.data.description}`).join(" ").toLowerCase();
    if (text.includes("next.js") || text.includes("nextjs")) return { framework: "Next.js", runtime: "Node.js", extension: "ts" };
    if (text.includes("react")) return { framework: "React + Vite", runtime: "Node.js", extension: "tsx" };
    if (text.includes("fastify")) return { framework: "Fastify", runtime: "Node.js", extension: "ts" };
    if (text.includes("express")) return { framework: "Express", runtime: "Node.js", extension: "ts" };
    if (text.includes("python")) return { framework: "Python service", runtime: "Python 3.12", extension: "py" };
    return { framework: "TypeScript service", runtime: "Node.js", extension: "ts" };
}

function projectName(nodes: ArchitectureNode[]): string {
    const primary = nodes.find((node) => node.data.type === "frontend") ?? nodes.find((node) => COMPUTE_TYPES.includes(node.data.type));
    return slug(primary?.data.label ?? "promptflow-app").replaceAll("-", "_").slice(0, 32);
}

function tsSourceFor(node: ArchitectureNode, edges: ArchitectureEdge[], byId: Map<string, ArchitectureNode>): string {
    const downstream = edges.filter((edge) => edge.source === node.id).map((edge) => byId.get(edge.target)?.data.label).filter(Boolean).slice(0, 6);
    const deps = downstream.length ? downstream.map((label) => `// → ${label}`).join("\n") : "// No downstream contract is represented yet.";
    return `/** ${node.data.label}\n * ${node.data.description}\n * Generated by PromptFlow Core 6. Treat this as a validated scaffold, not production-complete business logic.\n */\n\nexport interface ${typeIdentifier(node.data.label)}Config {\n  name: string;\n}\n\nexport async function ${identifier(node.data.label)}(): Promise<{ status: "ok"; component: string }> {\n  ${deps}\n  return { status: "ok", component: ${JSON.stringify(node.data.label)} };\n}\n`;
}

function pythonSourceFor(node: ArchitectureNode): string {
    const name = slug(node.data.label).replaceAll("-", "_");
    return `"""${node.data.description}\nGenerated by PromptFlow Core 6.\n"""\n\n\ndef ${name}() -> dict[str, str]:\n    return {"status": "ok", "component": ${JSON.stringify(node.data.label)}}\n`;
}

function frontendSourceFor(node: ArchitectureNode): string {
    return `import { useEffect, useState } from "react";\n\nexport function App() {\n  const [status, setStatus] = useState("connecting");\n\n  useEffect(() => {\n    setStatus("ready");\n  }, []);\n\n  return (\n    <main>\n      <h1>{${JSON.stringify(node.data.label)}}</h1>\n      <p>{${JSON.stringify(node.data.description)}}</p>\n      <p>Runtime: {status}</p>\n    </main>\n  );\n}\n`;
}

function testFor(node: ArchitectureNode, sourceContent: string): string {
    const fn = identifier(node.data.label);
    const hasGeneratedBoundary = new RegExp(
        `export\\s+(?:async\\s+)?function\\s+${fn}\\s*\\(`,
    ).test(sourceContent);

    if (!hasGeneratedBoundary) {
        return `await import("./${slug(node.data.label)}");
`;
    }

    return `import { ${fn} } from "./${slug(node.data.label)}";

const result = await ${fn}();
if (!result || result.status !== "ok") {
  throw new Error(${JSON.stringify(`${node.data.label} did not return a healthy execution boundary.`)});
}
`;
}

function testRunnerSource(): string {
    return `import { readdir } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const componentDir = join(process.cwd(), "src", "components");
let entries: string[] = [];
try {
  entries = (await readdir(componentDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith(".test.ts"))
    .map((entry) => entry.name)
    .sort();
} catch (error) {
  const code = error && typeof error === "object" && "code" in error ? error.code : undefined;
  if (code !== "ENOENT") throw error;
}
  let failures = 0;

for (const file of entries) {
  try {
    await import(pathToFileURL(join(componentDir, file)).href);
    console.log(\`PASS \${file}\`);
  } catch (error) {
    failures += 1;
    console.error(\`FAIL \${file}\`, error);
  }
}

const exitCode = failures > 0 ? 1 : 0;
if (exitCode === 0) {
  console.log(\`PromptFlow tests passed: \${entries.length}/\${entries.length}\`);
}

// Generated application modules may initialize long-lived handles (for example
// an HTTP listener) during import. process.exitCode alone waits for those handles,
// which can keep npm test alive after every smoke test has already passed. All
// test imports above are awaited, so an explicit exit here is deterministic.
process.exit(exitCode);`;
}

